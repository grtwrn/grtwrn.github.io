#!/usr/bin/env python3
"""Build index.html and projects/<slug>.html from projects.json.

Edit projects.json, then run: python3 build.py
"""
import hashlib
import json
import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).parent
# Web3Forms access key: messages go to the inbox it was issued for; no address appears on the site.
WEB3FORMS_KEY = ""
GITHUB = "https://github.com/grtwrn"
TAGLINE = "Building tech for neurodivergence, wellbeing, and human connection."
ABOUT = (
    "I'm a builder. I make devices and tools that help people notice what's "
    "going on around them and inside them, and act on it. I studied computer engineering "
    "at Brown ('21), worked at NVIDIA as a hardware architect, and now I'm "
    "building full-time."
)
PLACEHOLDER = "Write-up and photos coming."
# Changes whenever style.css does, so browsers don't keep a stale cached copy.
CSS_VERSION = hashlib.sha1((ROOT / "style.css").read_bytes()).hexdigest()[:8]


def strip_tags(s):
    return re.sub(r"<[^>]+>", "", s)


def excerpt(text, limit=140):
    text = strip_tags(text)
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def monogram(title):
    words = [w for w in re.split(r"[\s:]+", title) if w]
    return "".join(w[0] for w in words[:2]).upper()


GLYPH_COLORS = ["#24453a", "#3a4a52", "#1f7a55", "#7a6a48", "#10221b"]


def glyph_color(p):
    return GLYPH_COLORS[sum(map(ord, p["slug"])) % len(GLYPH_COLORS)]


def head_html(p, prefix):
    image = p.get("tileImage") or p.get("image")  # tileImage: optional square-friendly photo for the grid
    if image:
        pos = p.get("tilePosition") or p.get("imagePosition", "50% 50%")
        return (f'<div class="tile-head" style="background-image: url(\'{prefix}{image}\'); '
                f'background-position: {pos};"></div>')
    return (f'<div class="tile-head tile-head-glyph" style="background: {glyph_color(p)};">'
            f'<span>{escape(monogram(p["title"]))}</span></div>')


def tags_html(tags):
    return " ".join(f"#{escape(t)}" for t in tags)


def tile(p):
    summary = PLACEHOLDER if p.get("placeholder") else excerpt(p["summary"])
    meta = []
    if p.get("context") or p.get("status"):
        meta.append(" · ".join(x for x in (p.get("context"), p.get("status")) if x))
    if p.get("people"):
        meta.append(escape(p["people"]))
    if p.get("tags"):
        meta.append(tags_html(p["tags"]))
    meta_html = "".join(f"<div>{m}</div>" for m in meta)
    return f"""
      <a class="tile" id="p-{p['slug']}" href="projects/{p['slug']}.html">
        {head_html(p, '')}
        <div class="tile-body">
          <h2 class="tile-title">{escape(p['title'])}</h2>
          <p class="tile-excerpt">{escape(summary)}</p>
          <footer class="tile-meta">{meta_html}</footer>
        </div>
      </a>"""


# The contact form (and its nav link) only appear once WEB3FORMS_KEY is set.
CONTACT_NAV = '    <a href="{prefix}index.html#contact">Contact</a>\n' if WEB3FORMS_KEY else ""


def contact_html():
    if not WEB3FORMS_KEY:
        return ""
    return f"""
  <section class="contact" id="contact">
    <h2 class="grid-heading">Contact</h2>
    <form class="contact-form" action="https://api.web3forms.com/submit" method="POST">
      <input type="hidden" name="access_key" value="{WEB3FORMS_KEY}">
      <input type="hidden" name="subject" value="New message from your portfolio site">
      <input type="checkbox" name="botcheck" class="contact-botcheck" tabindex="-1" autocomplete="off">
      <label>Name<input type="text" name="name" required autocomplete="name"></label>
      <label>Email<input type="email" name="email" required autocomplete="email"></label>
      <label>Message<textarea name="message" rows="6" required></textarea></label>
      <button type="submit">Send</button>
    </form>
  </section>
"""


def topbar(prefix):
    return f"""
<header class="topbar">
  <a class="wordmark" href="{prefix}index.html">Garrett<br>Warren</a>
  <nav>
    <a href="{prefix}index.html#featured">Featured</a>
    <a href="{prefix}index.html#projects">Projects</a>
    <a href="{prefix}index.html#classes">Classes</a>
    <a href="{prefix}index.html#about">About</a>
{CONTACT_NAV.format(prefix=prefix)}  </nav>
</header>"""


def page(title, body, prefix):
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{escape(title)}</title>
<link rel="stylesheet" href="{prefix}style.css?v={CSS_VERSION}">
</head>
<body>
<!-- Generated by build.py from projects.json; edit those, not this file. -->
{topbar(prefix)}
{body}
<footer class="site-footer">&copy; 2026 Garrett Warren</footer>
</body>
</html>
"""


TIMELINE_SCRIPT = """
      <script>
        const links = document.querySelectorAll(".timeline ul a");
        const seen = new IntersectionObserver(entries => {
          for (const e of entries) {
            if (!e.isIntersecting) continue;
            links.forEach(a => a.classList.toggle("current", a.hash === "#" + e.target.id));
          }
        }, { rootMargin: "-40% 0px -55% 0px" });
        links.forEach(a => seen.observe(document.querySelector(a.hash)));
      </script>"""


def end_year(p):
    years = re.findall(r"\d{4}", p.get("context") or "")
    return int(years[-1]) if years else 0


def timeline_html(projects):
    years = {}
    for p in projects:
        years.setdefault(end_year(p), []).append(p)
    items = "".join(
        f'<li><p class="timeline-year"><a href="#p-{ps[0]["slug"]}">{y}</a></p><ul>'
        + "".join(f'<li><a href="#p-{p["slug"]}">{escape(p["title"])}</a></li>' for p in ps)
        + "</ul></li>"
        for y, ps in years.items())
    return f"""
      <aside class="timeline">
        <ol>{items}</ol>
      </aside>""" + TIMELINE_SCRIPT


def classes_html(edu):
    def course(c):
        title = escape(c[1])
        if len(c) > 2:
            title = f'<a href="projects/{c[2]}.html">{title}</a>'
        return f'<li><span class="course-code">{escape(c[0])}</span>{title}</li>'
    groups = "".join(
        f'<div class="class-group"><h3>{escape(g["name"])}</h3><ul>'
        + "".join(course(c) for c in g["courses"]) + "</ul></div>"
        for g in edu["groups"])
    return f"""
  <section class="classes" id="classes">
    <h2 class="grid-heading">Classes</h2>
    <p class="classes-degree">{escape(edu["school"])} · {escape(edu["degree"])} · {escape(edu["year"])}</p>
    <div class="class-groups">{groups}</div>
  </section>
"""


def build_index(data):
    by_slug = {p["slug"]: p for p in data["projects"]}
    featured = "".join(tile(by_slug[s]) for s in data["featured"])
    more = sorted([p for p in data["projects"] if p["slug"] not in data["featured"]] + data["housePrints"],
                  key=end_year, reverse=True)
    projects = "".join(tile(p) for p in more)
    body = f"""
<section class="hero">
  <div class="hero-content">
    <p class="hero-name">Garrett Warren</p>
    <h1>{escape(TAGLINE)}</h1>
  </div>
</section>

<main>
  <h2 class="grid-heading grid-heading-first" id="featured">Featured</h2>
  <div class="grid grid-full">{featured}
  </div>

  <h2 class="grid-heading" id="projects">More Projects</h2>
  <div class="projects-layout">{timeline_html(more)}
    <div class="grid grid-3">{projects}
    </div>
  </div>

{classes_html(data["education"])}
  <section class="about" id="about">
    <h2 class="grid-heading">About</h2>
    <p>{escape(ABOUT)}</p>
    <p><a href="{GITHUB}">github.com/grtwrn</a></p>
  </section>

{contact_html()}</main>"""
    (ROOT / "index.html").write_text(page("Garrett Warren", body, ""))


def build_project(p):
    prefix = "../"
    if p.get("image"):
        hero = (f'<div class="project-hero" style="background-image: url(\'{prefix}{p["image"]}\'); '
                f'background-position: {p.get("imagePosition", "50% 50%")};"></div>')
    else:
        hero = f'<div class="project-hero tile-head-glyph" style="background: {glyph_color(p)};"><span>{escape(monogram(p["title"]))}</span></div>'
    if p.get("placeholder"):
        paras = f'<p class="todo">{PLACEHOLDER}</p>'
    else:
        paras = "".join(f"<p>{para}</p>" for para in p["body"])
        paras += "".join(
            f'<figure class="project-shot{" wide" if img.get("wide") else ""}">'
            + (f'<video src="{prefix}{escape(img["video"])}" poster="{prefix}{escape(img["src"])}" controls muted loop playsinline preload="metadata" aria-label="{escape(img["alt"])}"></video>'
               if img.get("video") else f'<img src="{prefix}{escape(img["src"])}" alt="{escape(img["alt"])}">')
            + (f'<figcaption>{img["caption"]}</figcaption>' if img.get("caption") else "") + '</figure>'
            for img in p.get("screenshots", []))
    facts = []
    if p.get("context"):
        facts.append(escape(p["context"]))
    if p.get("status"):
        facts.append(f"Status: {escape(p['status'])}")
    if p.get("people"):
        facts.append(escape(p["people"]))
    for link in p.get("links", []):
        url = link["url"] if link["url"].startswith("http") else prefix + link["url"]
        facts.append(f'<a href="{escape(url)}">{escape(link["label"])}</a>')
    if p.get("tags"):
        facts.append(tags_html(p["tags"]))
    facts_html = "".join(f"<li>{f}</li>" for f in facts)
    body = f"""
{hero}
<main class="project-page">
  <aside class="sidebar">
    <a class="back" href="{prefix}index.html#projects">&lsaquo; Projects</a>
    <hr>
    <ul class="project-facts">{facts_html}</ul>
  </aside>
  <article>
    <h1>{escape(p['title'])}</h1>
    {paras}
  </article>
</main>"""
    out = ROOT / "projects" / f"{p['slug']}.html"
    out.write_text(page(f"{p['title']} · Garrett Warren", body, prefix))


def main():
    data = json.loads((ROOT / "projects.json").read_text())
    for key in ("projects", "housePrints"):
        for p in data[key]:
            if p.get("hidden"):
                (ROOT / "projects" / f"{p['slug']}.html").unlink(missing_ok=True)
        data[key] = [p for p in data[key] if not p.get("hidden")]
    (ROOT / "projects").mkdir(exist_ok=True)
    build_index(data)
    for p in data["projects"] + data["housePrints"]:
        build_project(p)


if __name__ == "__main__":
    main()
